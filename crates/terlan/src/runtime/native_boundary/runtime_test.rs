/// Verifies process-scoped Postgres calls require the manifest capability.
#[test]
fn runtime_enforces_postgres_capability_before_adapter_execution() {
    let mut runtime = NativeBoundaryRuntime::new();
    let config = NativeBoundaryTerm::PostgresConfig(postgres::Config::new("sqlite://local.db"));

    for granted_capabilities in [&[][..], &["filesystem.path"][..]] {
        assert_eq!(
            runtime.call_for_process_with_capabilities(
                7,
                granted_capabilities,
                "std.db.postgres.connect",
                std::slice::from_ref(&config),
            ),
            NativeBoundaryReplyTerm::Error {
                code: String::from("native_boundary.capability_denied"),
                message: String::from(
                    "NativeBoundary operation `std.db.postgres.connect` requires capability `postgres`."
                ),
                offset: 0,
            }
        );
    }

    assert_eq!(
        runtime.call_for_process_with_capabilities(
            7,
            &["postgres"],
            "std.db.postgres.connect",
            &[config],
        ),
        NativeBoundaryReplyTerm::Error {
            code: String::from("native_boundary.scheduler_denied"),
            message: String::from(
                "NativeBoundary operation `std.db.postgres.connect` requires `resource-owning` scheduler admission."
            ),
            offset: 0,
        }
    );

    assert_eq!(
        runtime.call_for_process_with_policy(
            7,
            &["postgres"],
            &[NativeBoundaryWorkerClass::ResourceOwning],
            "std.db.postgres.connect",
            &[NativeBoundaryTerm::PostgresConfig(postgres::Config::new(
                "sqlite://local.db",
            ))],
        ),
        NativeBoundaryReplyTerm::Error {
            code: String::from("postgres.invalid_url"),
            message: String::from("Postgres connection URL scheme `sqlite` is not supported."),
            offset: 0,
        }
    );
}


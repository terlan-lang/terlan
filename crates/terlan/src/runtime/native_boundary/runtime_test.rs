/// Extracts a handle from a successful reply term.
///
/// Inputs:
/// - `reply`: runtime reply expected to contain a handle.
///
/// Output:
/// - `Some(handle)` when the reply is a handle success.
/// - `None` after asserting the reply had an unexpected shape.
///
/// Transformation:
/// - Pattern-matches the stable reply term without unwrap/expect.
fn handle_reply(reply: NativeBoundaryReplyTerm) -> Option<NativeBoundaryHandle> {
    let NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Handle { id, generation }) = reply else {
        return None;
    };
    Some(NativeBoundaryHandle { id, generation })
}

/// Builds a handle term from a runtime handle.
///
/// Inputs:
/// - `handle`: opaque runtime handle.
///
/// Output:
/// - Stable term that carries the handle id and generation.
///
/// Transformation:
/// - Copies handle identity into the term shape expected by runtime calls.
fn handle_term(handle: NativeBoundaryHandle) -> NativeBoundaryTerm {
    NativeBoundaryTerm::Handle {
        id: handle.id,
        generation: handle.generation,
    }
}

/// Verifies cancellation is checked after admission and before adapter entry.
#[test]
fn runtime_policy_dispatch_observes_cooperative_cancellation() {
    let mut runtime = NativeBoundaryRuntime::new();
    let cancellation = NativeBoundaryCancellationToken::new();
    cancellation.cancel();

    let reply = runtime.call_for_process_with_policy_and_cancellation(
        7,
        &["postgres"],
        &[crate::terlan_native_boundary::metadata::NativeBoundaryWorkerClass::ResourceOwning],
        "std.db.postgres.connect",
        &[NativeBoundaryTerm::PostgresConfig(postgres::Config::new(
            "postgres://localhost/terlan",
        ))],
        &cancellation,
    );

    let error = crate::terlan_native_boundary::error::error_for(
        crate::terlan_native_boundary::error::ErrorKind::Cancelled,
    );
    assert_eq!(
        reply,
        NativeBoundaryReplyTerm::Error {
            code: error.code.to_string(),
            message: error.message.to_string(),
            offset: 0,
        }
    );
}


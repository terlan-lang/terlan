/// Verifies one VM process cannot dispatch with another process's handle.
#[test]
fn runtime_rejects_cross_process_resource_access() {
    let mut runtime = NativeBoundaryRuntime::new();
    let Some(root) = handle_reply(runtime.call_for_process(
        7,
        "std.data.json.parse",
        &[NativeBoundaryTerm::Text(String::from("null"))],
    )) else {
        return;
    };

    assert_eq!(
        runtime.call_for_process(8, "std.data.json.is_null", &[handle_term(root)],),
        NativeBoundaryReplyTerm::Error {
            code: String::from("resource.owner"),
            message: String::from(
                "NativeBoundary resource handle 1 belongs to process 7, not process 8."
            ),
            offset: 0,
        }
    );
    assert_eq!(
        runtime.call_for_process(7, "std.data.json.is_null", &[handle_term(root)]),
        NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Bool(true))
    );
}


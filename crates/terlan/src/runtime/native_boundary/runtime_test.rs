/// Verifies Postgres resources are disposed through VM-owned runtime handles.
///
/// Inputs:
/// - Disconnected Postgres pool fixture and synthetic row fixture registered
///   as NativeBoundary resources.
///
/// Output:
/// - Pool and row handles are live before disposal.
/// - Both handles become stable stale handles after disposal.
///
/// Transformation:
/// - Exercises Postgres-specific resource cleanup without opening a live
///   database connection or leaking Rust adapter values through VM terms.
#[test]
fn runtime_disposes_postgres_pool_and_row_resources() {
    let mut runtime = NativeBoundaryRuntime::new();
    let pool = runtime
        .resources
        .insert(ResourceValue::PostgresPool(
            postgres::test_support::disconnected_pool("postgres://localhost/terlan"),
        ))
        .expect("pool handle should allocate");
    let mut row = postgres::Row::new();
    row.put_string("status", "ok");
    let row = runtime
        .resources
        .insert(ResourceValue::PostgresRow(row))
        .expect("row handle should allocate");

    assert_eq!(
        runtime.call(
            "std.db.postgres.string",
            &[
                handle_term(row),
                NativeBoundaryTerm::Text(String::from("status"))
            ],
        ),
        NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Text(String::from("ok")))
    );
    assert_eq!(
        runtime.dispose(pool),
        NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Unit)
    );
    assert_eq!(
        runtime.dispose(row),
        NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Unit)
    );

    assert_eq!(
        runtime.call(
            "std.db.postgres.execute",
            &[
                handle_term(pool),
                NativeBoundaryTerm::Text(String::from("SELECT 1")),
                NativeBoundaryTerm::List(Vec::new()),
            ],
        ),
        NativeBoundaryReplyTerm::Error {
            code: String::from("resource.stale_handle"),
            message: String::from("NativeBoundary resource handle 1 generation 1 is not live."),
            offset: 0,
        }
    );
    assert_eq!(
        runtime.call(
            "std.db.postgres.string",
            &[
                handle_term(row),
                NativeBoundaryTerm::Text(String::from("status"))
            ],
        ),
        NativeBoundaryReplyTerm::Error {
            code: String::from("resource.stale_handle"),
            message: String::from("NativeBoundary resource handle 2 generation 1 is not live."),
            offset: 0,
        }
    );
}


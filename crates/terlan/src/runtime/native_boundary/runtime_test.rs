/// Verifies Postgres row accessors decode through VM NativeBoundary handles.
///
/// Inputs:
/// - Synthetic Postgres row resource with string, integer, boolean, and JSON
///   columns.
///
/// Output:
/// - Primitive column accessors return VM terms.
/// - JSON column accessor returns a JSON resource handle that can be decoded by
///   the JSON NativeBoundary adapter.
///
/// Transformation:
/// - Exercises Postgres row decoding through the same resource handle surface
///   used by live query results without requiring a database.
#[test]
fn runtime_decodes_postgres_row_columns_through_handles() {
    let mut runtime = NativeBoundaryRuntime::new();
    let mut row = postgres::Row::new();
    row.put_string("name", "Ada");
    row.put_int("age", 42);
    row.put_bool("active", true);
    row.put_json("meta", json::string("ok"));
    let row = runtime
        .resources
        .insert(ResourceValue::PostgresRow(row))
        .expect("row handle should allocate");

    assert_eq!(
        runtime.call(
            "std.db.postgres.string",
            &[
                handle_term(row),
                NativeBoundaryTerm::Text(String::from("name"))
            ],
        ),
        NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Text(String::from("Ada")))
    );
    assert_eq!(
        runtime.call(
            "std.db.postgres.int",
            &[
                handle_term(row),
                NativeBoundaryTerm::Text(String::from("age"))
            ],
        ),
        NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Int(42))
    );
    assert_eq!(
        runtime.call(
            "std.db.postgres.bool",
            &[
                handle_term(row),
                NativeBoundaryTerm::Text(String::from("active"))
            ],
        ),
        NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Bool(true))
    );
    let Some(meta) = handle_reply(runtime.call(
        "std.db.postgres.json",
        &[
            handle_term(row),
            NativeBoundaryTerm::Text(String::from("meta")),
        ],
    )) else {
        return;
    };
    assert_eq!(
        runtime.call("std.data.json.as_string", &[handle_term(meta)]),
        NativeBoundaryReplyTerm::Ok(NativeBoundaryTerm::Text(String::from("ok")))
    );
}

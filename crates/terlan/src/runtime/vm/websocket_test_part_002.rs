
/// Verifies VM WebSocket sessions account text traffic over VM TCP.
///
/// Inputs:
/// - VM TCP client/server stream pair.
/// - One client text frame and one server text frame.
///
/// Output:
/// - Test passes when received/sent frame and byte counters match the VM TCP
///   traffic.
///
/// Transformation:
/// - Proves session inspection is VM-owned while frame bytes still round-trip
///   through maintained tungstenite encoding.
#[test]
fn vm_websocket_session_tracks_text_traffic() {
    let (mut tcp, client, server) = connected_tcp_pair();
    let mut session = VmWebSocketSession::new(server);
    let incoming = encode_client_text_frame("session in");
    let incoming_len = incoming.len();
    tcp.send(client, incoming).expect("send client text frame");

    let received = session
        .receive_text(&mut tcp, 4096)
        .expect("receive session text")
        .expect("queued session text");

    assert_eq!(received, "session in");
    assert_eq!(
        session.inspect(),
        VmWebSocketSessionInfo {
            stream: server,
            open: true,
            frames_sent: 0,
            frames_received: 1,
            bytes_sent: 0,
            bytes_received: incoming_len,
        }
    );

    let written = session
        .send_text(&mut tcp, "session out")
        .expect("send session text");
    let outgoing = tcp
        .receive(client, written)
        .expect("receive server text frame")
        .expect("queued server text frame");

    assert_eq!(decode_server_text_frame(&outgoing), "session out");
    assert_eq!(
        session.inspect(),
        VmWebSocketSessionInfo {
            stream: server,
            open: true,
            frames_sent: 1,
            frames_received: 1,
            bytes_sent: written,
            bytes_received: incoming_len,
        }
    );
}


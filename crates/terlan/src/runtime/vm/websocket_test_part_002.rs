/// Verifies the VM WebSocket runtime isolates multiple sessions.
///
/// Inputs:
/// - One VM TCP runtime with two independent client/server stream pairs.
/// - One WebSocket session per accepted server stream.
///
/// Output:
/// - Test passes when each session receives only its own stream traffic and
///   inspection counters stay independent.
///
/// Transformation:
/// - Proves production WebSocket handlers can keep session ownership in the VM
///   registry instead of ad hoc HTTP-layer maps.
#[test]
fn vm_websocket_runtime_routes_sessions_independently() {
    let mut tcp = VmTcpRuntime::new();
    let (client_a, server_a) = connected_tcp_pair_at(&mut tcp, "websocket.a");
    let (client_b, server_b) = connected_tcp_pair_at(&mut tcp, "websocket.b");
    let mut runtime = VmWebSocketRuntime::new();
    let session_a = runtime.open_session(server_a);
    let session_b = runtime.open_session(server_b);
    let frame_a = encode_client_text_frame("alpha");
    let frame_b = encode_client_text_frame("beta");
    let frame_a_len = frame_a.len();
    let frame_b_len = frame_b.len();
    tcp.send(client_a, frame_a).expect("send alpha");
    tcp.send(client_b, frame_b).expect("send beta");

    let beta = runtime
        .receive_frame(&mut tcp, session_b, 4096)
        .expect("receive beta")
        .expect("queued beta");
    let alpha = runtime
        .receive_frame(&mut tcp, session_a, 4096)
        .expect("receive alpha")
        .expect("queued alpha");

    assert_eq!(runtime.session_count(), 2);
    assert_eq!(beta, VmWebSocketFrame::Text("beta".to_string()));
    assert_eq!(alpha, VmWebSocketFrame::Text("alpha".to_string()));
    assert_eq!(
        runtime.inspect_session(session_a).expect("inspect alpha"),
        VmWebSocketSessionInfo {
            stream: server_a,
            open: true,
            frames_sent: 0,
            frames_received: 1,
            bytes_sent: 0,
            bytes_received: frame_a_len,
        }
    );
    assert_eq!(
        runtime.inspect_session(session_b).expect("inspect beta"),
        VmWebSocketSessionInfo {
            stream: server_b,
            open: true,
            frames_sent: 0,
            frames_received: 1,
            bytes_sent: 0,
            bytes_received: frame_b_len,
        }
    );
}

